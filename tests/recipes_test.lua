package.path = "Scripts/?.lua;" .. package.path
local Recipes = require("recipes")
local function equal(actual, expected) assert(actual == expected, tostring(actual) .. " ~= " .. tostring(expected)) end
local tracker = Recipes.new_tracker()
local row = {Product_Count = 3, Material1_Id = "Wood", Material1_Count = 10,
    Material2_Id = "Stone", Material2_Count = 5, Material3_Id = "Wood", Material3_Count = 2,
    Material4_Id = "None", Material4_Count = 100, Material5_Id = "Fiber", Material5_Count = 0}
local recipe = Recipes.from_row("craft", "Arrow", row, "Arrow")
equal(recipe.output, 3)
equal(#recipe.materials, 2)
equal(recipe.materials[1].count, 12)
equal(Recipes.from_row("craft", "None", row), nil)
equal(Recipes.from_row("build", "FreeObject", {}), nil)
local free = Recipes.from_row("craft", "FreeRecipe", {Product_Id = "FreeItem"})
assert(free and #free.materials == 0, "A valid zero-cost recipe must remain pinnable")
equal(Recipes.toggle(tracker, recipe), true)
equal(Recipes.is_pinned(tracker, recipe), true)
equal(tracker.version, 1)
equal(tracker.by_key[recipe.key], tracker.pins[1])
recipe.materials[1].count = 999
equal(tracker.pins[1].materials[1].count, 12)
local building = Recipes.from_row("build", "Arrow", {Material1_Id = "Wood", Material1_Count = 20}, "Building")
equal(Recipes.toggle(tracker, building), true)
equal(#tracker.pins, 2)
local owned = {Wood = 30, Stone = 0}
local function display(page) return Recipes.display(tracker, page or 1, function(id) return id end, function(id) return owned[id] end) end
local cards = display()
equal(cards[1].title, "Arrow x3")
equal(cards[1].materials[1].text, "Wood: 30/12")
equal(cards[1].materials[1].complete, true)
equal(cards[1].materials[2].text, "Stone: 0/5")
equal(cards[1].materials[2].complete, false)
owned.Wood = 8
equal(display()[1].materials[1].text, "Wood: 8/12")
equal(display()[1].materials[1].complete, false)
local unknown = Recipes.display(tracker, 1, function(id) return id end)
equal(unknown[1].materials[1].text, "Wood: ?/12")
equal(unknown[1].materials[1].complete, false)
equal(Recipes.toggle(tracker, recipe), false)
equal(tracker.by_key[recipe.key], nil)
equal(Recipes.is_pinned(tracker, building), true)
equal(#tracker.pins, 1)
equal(Recipes.toggle(tracker, nil), false)
for index = 1, 6 do Recipes.toggle(tracker, Recipes.from_row("craft", "Pin" .. index, {Product_Id = "Wood"}, "Pin " .. index)) end
local first, page, pages = display()
equal(#first, 5)
equal(page, 1)
equal(pages, 2)
local second = display(2)
equal(#second, 2)
equal(second[1].title, "Pin 5")
local last, clamped = display(99)
equal(#last, 2)
equal(clamped, 2)
equal(tracker.pins[7].icon_id, "Wood")
local before_clear = tracker.version
Recipes.clear(tracker)
equal(#tracker.pins, 0)
equal(next(tracker.by_key), nil)
equal(tracker.version, before_clear + 1)
equal(Recipes.is_pinned(tracker, building), false)
print("Recipe tests passed: costs, batch yield, duplicate ingredients, detached pins, craft/build IDs, unpin.")
